// Builds supabase/functions/_shared/legal-topic-embeddings.ts using the open-source
// gte-small model (the same model Supabase Edge Functions run for free).
// Run after changing topics in legal-knowledge.ts:
//   npm i --no-save @huggingface/transformers@3 && node scripts/build-topic-embeddings.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { transformSync } from "esbuild";
import { pipeline } from "@huggingface/transformers";

const src = readFileSync(new URL("../supabase/functions/_shared/legal-knowledge.ts", import.meta.url), "utf8");
const { code } = transformSync(src, { loader: "ts", format: "esm" });
const kb = await import(`data:text/javascript;base64,${Buffer.from(code).toString("base64")}`);

const extractor = await pipeline("feature-extraction", "Supabase/gte-small");
const rows = [];
for (const t of kb.LEGAL_TOPICS) {
  const texts = [
    `${t.title}. ${t.overview}`,
    `${t.title}: ${t.keywords.join(", ")}`,
    ...t.steps.slice(0, 2).map((s) => `${t.title}: ${s}`),
  ];
  const out = await extractor(texts, { pooling: "mean", normalize: true });
  for (const v of out.tolist()) rows.push({ id: t.id, vector: v.map((x) => Math.round(x * 1e4) / 1e4) });
}
const body = `// Generated by scripts/build-topic-embeddings.mjs. Do not edit by hand.\n// Model: Supabase/gte-small (384 dims, mean pooled, normalized).\nimport type { TopicEmbedding } from "./legal-knowledge.ts";\n\nexport const TOPIC_EMBEDDINGS: TopicEmbedding[] = ${JSON.stringify(rows)};\n`;
writeFileSync(new URL("../supabase/functions/_shared/legal-topic-embeddings.ts", import.meta.url), body);
console.log(`wrote ${rows.length} vectors for ${kb.LEGAL_TOPICS.length} topics`);
